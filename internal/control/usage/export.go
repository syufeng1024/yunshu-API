// K27 lock
// ---------------------------------------------------------------------------

func (s *Service) acquireExportLock(ctx context.Context, uid int64) (bool, *apierr.APIError) {
	if s.Redis == nil {
		return false, apierr.New(apierr.CodeInternalError)
	}
	cmdCtx, cancel := s.Redis.CommandContext(ctx)
	defer cancel()
	ok, err := s.Redis.Raw().SetNX(cmdCtx, redisx.ExportLockKey(uid), "1", s.exportTTL()).Result()
	if err != nil {
		s.logError(ctx, "usage_export_lock_failed: "+err.Error())
		return false, apierr.New(apierr.CodeInternalError)
	}
	return ok, nil
}

func (s *Service) exportLockExists(ctx context.Context, uid int64) bool {
	if s.Redis == nil {
		return false
	}
	cmdCtx, cancel := s.Redis.CommandContext(ctx)
	defer cancel()
	n, err := s.Redis.Raw().Exists(cmdCtx, redisx.ExportLockKey(uid)).Result()
	return err == nil && n > 0
}

// releaseExportLock is used only on failure. A successful task keeps the lock
// for its full hour so the "one running export per account" rule also covers
// back-to-back requests within the download window.
func (s *Service) releaseExportLock(ctx context.Context, uid int64) {
	if s.Redis == nil {
		return
	}
	ctx, cancel := context.WithTimeout(context.WithoutCancel(ctx), 2*time.Second)
	defer cancel()
	cmdCtx, cancelCmd := s.Redis.CommandContext(ctx)
	defer cancelCmd()
	_ = s.Redis.Raw().Del(cmdCtx, redisx.ExportLockKey(uid)).Err()
}

