// Exporter stores one finished CSV. The repository has no object store in
// V1.0, so the default implementation writes a local file; a future
// deployment can swap the implementation without touching the task logic.
type Exporter interface {
	Put(ctx context.Context, name string, data []byte) (ref string, err error)
	Open(ctx context.Context, ref string) ([]byte, error)
}

// FileExporter writes to Dir. Names are generated by the service as 16 random
// bytes in hex, never from user input, and validated again here so a name can
// never escape the directory.
type FileExporter struct {
	Dir string
}

var exportNamePattern = regexp.MustCompile(`^[0-9a-f]{32}\.csv$`)

func (f *FileExporter) Put(ctx context.Context, name string, data []byte) (string, error) {
	if !exportNamePattern.MatchString(name) {
		return "", fmt.Errorf("usage: unsafe export name %q", name)
	}
	if err := ctx.Err(); err != nil {
		return "", err
	}
	if err := os.MkdirAll(f.Dir, 0o700); err != nil {
		return "", fmt.Errorf("usage: create export dir: %w", err)
	}
	tmp, err := os.CreateTemp(f.Dir, ".tmp-*")
	if err != nil {
		return "", fmt.Errorf("usage: create temp export: %w", err)
	}
	tmpName := tmp.Name()
	defer func() { _ = os.Remove(tmpName) }()
	if err := tmp.Chmod(0o600); err != nil {
		_ = tmp.Close()
		return "", fmt.Errorf("usage: chmod temp export: %w", err)
	}
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return "", fmt.Errorf("usage: write temp export: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return "", fmt.Errorf("usage: close temp export: %w", err)
	}
	final := filepath.Join(f.Dir, name)
	if err := os.Rename(tmpName, final); err != nil {
		return "", fmt.Errorf("usage: publish export: %w", err)
	}
	return name, nil
}

func (f *FileExporter) Open(ctx context.Context, ref string) ([]byte, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	if !exportNamePattern.MatchString(ref) {
		return nil, os.ErrNotExist
	}
	return os.ReadFile(filepath.Join(f.Dir, ref))
}

// Exists is an optional capability on top of the two-method Exporter
// interface. Status polling runs every few seconds; reading a large CSV just
// to answer "is it there" would make polling cost the file size each time.
func (f *FileExporter) Exists(ctx context.Context, ref string) (bool, error) {
	if err := ctx.Err(); err != nil {
		return false, err
	}
	if !exportNamePattern.MatchString(ref) {
		return false, nil
	}
	_, err := os.Stat(filepath.Join(f.Dir, ref))
	if errors.Is(err, os.ErrNotExist) {
		return false, nil
	}
	if err != nil {
		return false, err
	}
	return true, nil
}

// exportStatter is implemented by FileExporter; a future object-store
// exporter can implement it without changing the Exporter contract.
type exportStatter interface {
	Exists(ctx context.Context, ref string) (bool, error)
}

func (s *Service) exportExists(ctx context.Context, file string) (bool, error) {
	if st, ok := s.Exporter.(exportStatter); ok {
		return st.Exists(ctx, file)
	}
	_, err := s.Exporter.Open(ctx, file)
	if err == nil {
		return true, nil
	}
	if errors.Is(err, os.ErrNotExist) {
		return false, nil
	}
	return false, err
}

// token kinds. The same path /api/console/exports/{token} carries both: the
// task token answers the status JSON, the download token streams the CSV. The
// kind is inside the signed payload, so a client cannot turn one into the
// other.
const (
	tokenKindTask     = "task"
	tokenKindDownload = "dl"

	exportStateRunning = "RUNNING"
	exportStateDone    = "DONE"
	exportStateFailed  = "FAILED"
)

var (
	errTokenInvalid = errors.New("usage: invalid export token")
	errTokenExpired = errors.New("usage: expired export token")
)

type tokenData struct {
	Kind      string
	UID       int64
	Exp       int64
	File      string
	ParamHash string
}

type exportStartResponse struct {
	TaskID string `json:"task_id"`
	State  string `json:"state"`
}

type exportStatusResponse struct {
	TaskID    string     `json:"task_id"`
	State     string     `json:"state"`
	URL       string     `json:"url,omitempty"`
	ExpiresAt *time.Time `json:"expires_at,omitempty"`
}

// StartExport implements POST /api/console/usage/export.
//
// The response is 202 plus a task token, never CSV bytes: the query runs in a
// detached goroutine so a 365-day export cannot hold the HTTP connection.
//
// Task state is not stored in a table. It is derived:
//
//	file exists                     -> DONE (the URL is a download token)
//	file absent, K27 exists         -> RUNNING
//	file absent, K27 absent         -> FAILED (worker exited without a file)
//
// The task token's own exp bounds all three to one hour, so a failed task
// cannot be polled forever.
func (s *Service) StartExport(w http.ResponseWriter, r *http.Request) {
	uid, apiErr := sessionUID(r)
	if apiErr != nil {
		mw.WriteError(w, r, apiErr)
		return
	}
	if len(s.HMACKey) == 0 {
		e := apierr.New(apierr.CodeConfigUnavailable)
		e.Message = "未配置导出密钥"
		e = e.WithHint("设置环境变量 EXPORT_HMAC_KEY 后重试")
		mw.WriteError(w, r, e)
		return
	}
	f, apiErr := s.parseUsageFilter(r.URL.Query())
	if apiErr != nil {
		mw.WriteError(w, r, apiErr)
		return
	}
	if s.Exporter == nil {
		mw.WriteError(w, r, apierr.New(apierr.CodeInternalError))
		return
	}

	file, err := randomExportName()
	if err != nil {
		s.logError(r.Context(), "usage_export_name_failed: "+err.Error())
		mw.WriteError(w, r, apierr.New(apierr.CodeInternalError))
		return
	}
	exp := s.now().Add(s.exportTTL())
	taskToken := s.signToken(tokenData{
		Kind: tokenKindTask, UID: uid, Exp: exp.Unix(),
		File: file, ParamHash: filterHash(f),
	})

	ok, apiErr := s.acquireExportLock(r.Context(), uid)
	if apiErr != nil {
		mw.WriteError(w, r, apiErr)
		return
	}
	if !ok {
		e := apierr.New(apierr.CodeResourceStateConflict)
		e.Message = "已有导出任务进行中"
		e = e.WithHint("单个账号同时只能运行 1 个导出任务，请等待当前任务完成或 1 小时后重试")
		mw.WriteError(w, r, e)
		return
	}

	// Detach from the request context: returning 202 cancels r.Context(), and
	// the worker must survive it. WithoutCancel keeps values (trace id) but
	// drops cancellation; the timeout is the worker's own bound.
	base := context.WithoutCancel(r.Context())
	go func() {
		ctx, cancel := context.WithTimeout(base, exportTimeout)
		defer cancel()
		if err := s.writeExportCSV(ctx, uid, f, file); err != nil {
			s.logError(ctx, "usage_export_failed: "+err.Error())
			s.releaseExportLock(ctx, uid)
		}
	}()

	_ = mw.WriteJSON(w, http.StatusAccepted, exportStartResponse{
		TaskID: taskToken, State: exportStateRunning,
	})
}

func (s *Service) writeExportCSV(ctx context.Context, uid int64, f usageFilter, file string) error {
	rows, apiErr := s.fetchUsageRows(ctx, uid, f)
	if apiErr != nil {
		// fetchUsageRows already logged the SQL failure. Its APIError is for
		// the HTTP surface; here the state is simply FAILED.
		return errors.New("usage: export aggregation failed")
	}

	var buf bytes.Buffer
	cw := csv.NewWriter(&buf)
	if err := cw.Write(usageColumnHeaders()); err != nil {
		return err
	}
	for _, row := range rows {
		if err := cw.Write(usageCSVRecord(row)); err != nil {
			return err
		}
	}
	cw.Flush()
	if err := cw.Error(); err != nil {
		return err
	}
	_, err := s.Exporter.Put(ctx, file, buf.Bytes())
	return err
}

// ExportToken implements GET /api/console/exports/{token}. It answers JSON
// for a task token and the CSV bytes for a download token.
func (s *Service) ExportToken(w http.ResponseWriter, r *http.Request) {
	uid, apiErr := sessionUID(r)
	if apiErr != nil {
		mw.WriteError(w, r, apiErr)
		return
	}
	raw := r.PathValue("token")
	data, err := s.verifyToken(raw, s.now())
	if errors.Is(err, errTokenExpired) {
		e := apierr.New(apierr.CodeResourceNotFound)
		e.Message = "导出链接已失效"
		e = e.WithHint("导出链接有效期为 1 小时，请重新发起导出")
		mw.WriteError(w, r, e)
		return
	}
	if err != nil {
		mw.WriteError(w, r, apierr.New(apierr.CodeResourceNotFound))
		return
	}
	// A valid token for someone else is indistinguishable from a missing one.
	if data.UID != uid {
		mw.WriteError(w, r, apierr.New(apierr.CodeResourceNotFound))
		return
	}

	switch data.Kind {
	case tokenKindDownload:
		s.download(w, r, data)
	case tokenKindTask:
		s.exportStatus(w, r, raw, data)
	default:
		mw.WriteError(w, r, apierr.New(apierr.CodeResourceNotFound))
	}
}

func (s *Service) exportStatus(w http.ResponseWriter, r *http.Request, raw string, data tokenData) {
	ctx := r.Context()
	state := exportStateFailed
	// The file's existence is the DONE fact (see the derivation comment on
	// StartExport). FileExporter answers with os.Stat; an exporter without the
	// optional Exists method falls back to Open.
	exists, err := s.exportExists(ctx, data.File)
	switch {
	case err != nil:
		s.logWarn(ctx, "usage_export_status_probe_failed: "+err.Error())
	case exists:
		state = exportStateDone
	case s.exportLockExists(ctx, data.UID):
		state = exportStateRunning
	}

	expires := time.Unix(data.Exp, 0).UTC()
	out := exportStatusResponse{
		TaskID: raw, State: state, ExpiresAt: &expires,
	}
	if state == exportStateDone {
		out.URL = "/api/console/exports/" + s.signToken(tokenData{
			Kind: tokenKindDownload, UID: data.UID, Exp: data.Exp, File: data.File,
		})
	}
	_ = mw.WriteJSON(w, http.StatusOK, out)
}

func (s *Service) download(w http.ResponseWriter, r *http.Request, data tokenData) {
	blob, err := s.Exporter.Open(r.Context(), data.File)
	if errors.Is(err, os.ErrNotExist) {
		e := apierr.New(apierr.CodeResourceNotFound)
		e.Message = "导出文件不存在或已失效"
		e = e.WithHint("导出链接有效期为 1 小时，请重新发起导出")
		mw.WriteError(w, r, e)
		return
	}
	if err != nil {
		s.logError(r.Context(), "usage_export_open_failed: "+err.Error())
		mw.WriteError(w, r, apierr.New(apierr.CodeInternalError))
		return
	}
	h := w.Header()
	h.Set("Content-Type", "text/csv; charset=utf-8")
	h.Set("Content-Disposition", `attachment; filename="usage-`+
		strconv.FormatInt(data.Exp, 10)+`.csv"`)
	h.Set("Cache-Control", "no-store")
	h.Set("X-Content-Type-Options", "nosniff")
	w.WriteHeader(http.StatusOK)
	_, _ = w.Write(blob)
}

