func randomExportName() (string, error) {
	var raw [16]byte
	if _, err := rand.Read(raw[:]); err != nil {
		return "", err
	}
	return hex.EncodeToString(raw[:]) + ".csv", nil
}

// filterHash binds a task token to the parameters it was created with. It is
// not used to re-read a task (the worker captures the filter); it makes two
// tasks with different filters distinguishable inside the signed payload.
func filterHash(f usageFilter) string {
	id := func(p *int64) string {
		if p == nil {
			return ""
		}
		return strconv.FormatInt(*p, 10)
	}
	canonical := strings.Join([]string{
		f.From.Format(time.RFC3339Nano), f.To.Format(time.RFC3339Nano),
		f.Dimension, id(f.ModelID), id(f.ChannelID),
	}, "|")
	sum := sha256.Sum256([]byte(canonical))
	return hex.EncodeToString(sum[:])
}
