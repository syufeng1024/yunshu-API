// signToken builds base64url(payload) "." base64url(HMAC-SHA256(payload)).
// The payload names the owner, the expiry, the random file and (for a task)
// the filter hash, so the server stores no task row.
func (s *Service) signToken(t tokenData) string {
	payload := strings.Join([]string{
		t.Kind, strconv.FormatInt(t.UID, 10), strconv.FormatInt(t.Exp, 10),
		t.File, t.ParamHash,
	}, "|")
	mac := hmac.New(sha256.New, s.HMACKey)
	mac.Write([]byte(payload))
	return base64.RawURLEncoding.EncodeToString([]byte(payload)) + "." +
		base64.RawURLEncoding.EncodeToString(mac.Sum(nil))
}

func (s *Service) verifyToken(raw string, now time.Time) (tokenData, error) {
	if len(s.HMACKey) == 0 {
		return tokenData{}, errTokenInvalid
	}
	parts := strings.SplitN(raw, ".", 2)
	if len(parts) != 2 {
		return tokenData{}, errTokenInvalid
	}
	payload, err := base64.RawURLEncoding.DecodeString(parts[0])
	if err != nil {
		return tokenData{}, errTokenInvalid
	}
	sig, err := base64.RawURLEncoding.DecodeString(parts[1])
	if err != nil {
		return tokenData{}, errTokenInvalid
	}
	mac := hmac.New(sha256.New, s.HMACKey)
	mac.Write(payload)
	if !hmac.Equal(sig, mac.Sum(nil)) {
		return tokenData{}, errTokenInvalid
	}
	fields := strings.Split(string(payload), "|")
	if len(fields) != 5 {
		return tokenData{}, errTokenInvalid
	}
	uid, err := strconv.ParseInt(fields[1], 10, 64)
	if err != nil || uid <= 0 {
		return tokenData{}, errTokenInvalid
	}
	exp, err := strconv.ParseInt(fields[2], 10, 64)
	if err != nil || exp <= 0 {
		return tokenData{}, errTokenInvalid
	}
	if !exportNamePattern.MatchString(fields[3]) {
		return tokenData{}, errTokenInvalid
	}
	if fields[0] != tokenKindTask && fields[0] != tokenKindDownload {
		return tokenData{}, errTokenInvalid
	}
	if now.Unix() >= exp {
		return tokenData{}, errTokenExpired
	}
	return tokenData{
		Kind: fields[0], UID: uid, Exp: exp,
		File: fields[3], ParamHash: fields[4],
	}, nil
}

